//! Standard Linux localization (`locale.conf` + GNU gettext `.po` / Slint `@tr` integration).
//!
//! Reads and writes `~/.config/penumbra/locale.conf` and `~/.config/locale.conf`
//! using standard `LANG` / `LANGUAGE` / `LC_MESSAGES` environment variables,
//! falling back to `"en"` (default English) whenever no translation exists.

use std::path::PathBuf;

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LanguageOption {
    pub code: &'static str,
    pub native_name: &'static str,
    pub locale: &'static str,
}

pub const SUPPORTED_LANGUAGES: &[LanguageOption] = &[
    LanguageOption {
        code: "en",
        native_name: "English (Default)",
        locale: "en_US.UTF-8",
    },
    LanguageOption {
        code: "ro",
        native_name: "Română",
        locale: "ro_RO.UTF-8",
    },
    LanguageOption {
        code: "de",
        native_name: "Deutsch",
        locale: "de_DE.UTF-8",
    },
    LanguageOption {
        code: "fr",
        native_name: "Français",
        locale: "fr_FR.UTF-8",
    },
    LanguageOption {
        code: "es",
        native_name: "Español",
        locale: "es_ES.UTF-8",
    },
    LanguageOption {
        code: "it",
        native_name: "Italiano",
        locale: "it_IT.UTF-8",
    },
];

pub fn penumbra_locale_conf_path() -> PathBuf {
    if let Ok(cfg) = std::env::var("XDG_CONFIG_HOME") {
        PathBuf::from(cfg).join("penumbra").join("locale.conf")
    } else if let Ok(home) = std::env::var("HOME") {
        PathBuf::from(home).join(".config").join("penumbra").join("locale.conf")
    } else {
        PathBuf::from("/etc/penumbra/locale.conf")
    }
}

pub fn user_locale_conf_path() -> PathBuf {
    if let Ok(cfg) = std::env::var("XDG_CONFIG_HOME") {
        PathBuf::from(cfg).join("locale.conf")
    } else if let Ok(home) = std::env::var("HOME") {
        PathBuf::from(home).join(".config").join("locale.conf")
    } else {
        PathBuf::from("/etc/locale.conf")
    }
}

/// Extracts the primary 2-letter language code from a POSIX locale string (e.g. `"ro_RO.UTF-8"` -> `"ro"`).
pub fn normalize_lang_code(raw: &str) -> String {
    let first = raw
        .split(':')
        .next()
        .unwrap_or("")
        .split('.')
        .next()
        .unwrap_or("")
        .split('_')
        .next()
        .unwrap_or("")
        .split('-')
        .next()
        .unwrap_or("")
        .trim()
        .to_lowercase();
    if first.is_empty() || first == "c" || first == "posix" {
        "en".to_string()
    } else {
        first
    }
}

fn parse_locale_file(path: &std::path::Path) -> Option<String> {
    let content = std::fs::read_to_string(path).ok()?;
    for key in ["LANGUAGE", "LC_ALL", "LC_MESSAGES", "LANG"] {
        for line in content.lines() {
            let trimmed = line.trim();
            if trimmed.starts_with('#') || trimmed.is_empty() {
                continue;
            }
            if let Some(val) = trimmed.strip_prefix(&format!("{key}=")) {
                let cleaned = val.trim().trim_matches('"').trim_matches('\'');
                if !cleaned.is_empty() {
                    return Some(normalize_lang_code(cleaned));
                }
            }
        }
    }
    None
}

/// Resolves the active language code from environment variables and `locale.conf`, defaulting to `"en"`.
pub fn active_lang_code() -> String {
    for path in [
        penumbra_locale_conf_path(),
        user_locale_conf_path(),
        PathBuf::from("/etc/locale.conf"),
    ] {
        if let Some(code) = parse_locale_file(&path) {
            return code;
        }
    }

    for var in ["LANGUAGE", "LC_ALL", "LC_MESSAGES", "LANG"] {
        if let Ok(val) = std::env::var(var) {
            if !val.trim().is_empty() {
                return normalize_lang_code(&val);
            }
        }
    }

    "en".to_string()
}

/// Persists the selected language to `~/.config/penumbra/locale.conf` and `~/.config/locale.conf`
/// in standard Linux `locale.conf` format (propagated to all apps by `penumbra-session`).
pub fn save_system_language(code: &str) -> std::io::Result<()> {
    let norm = normalize_lang_code(code);
    let locale = SUPPORTED_LANGUAGES
        .iter()
        .find(|l| l.code == norm)
        .map(|l| l.locale.to_string())
        .unwrap_or_else(|| {
            if norm == "en" {
                "en_US.UTF-8".to_string()
            } else {
                format!("{norm}_{}.UTF-8", norm.to_uppercase())
            }
        });

    let language_chain = if norm == "en" {
        "en_US:en".to_string()
    } else {
        format!("{norm}:en")
    };

    let content = format!(
        "# Generated by Penumbra Settings\nLANG={locale}\nLANGUAGE={language_chain}\nLC_MESSAGES={locale}\n"
    );

    for path in [penumbra_locale_conf_path(), user_locale_conf_path()] {
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)?;
        }
        std::fs::write(&path, &content)?;
    }

    // Update current process environment for child processes spawned from Settings/Shell
    std::env::set_var("LANG", &locale);
    std::env::set_var("LANGUAGE", &language_chain);
    std::env::set_var("LC_MESSAGES", &locale);

    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_normalize_lang_code() {
        assert_eq!(normalize_lang_code("ro_RO.UTF-8"), "ro");
        assert_eq!(normalize_lang_code("de_DE:de:en"), "de");
        assert_eq!(normalize_lang_code("C.UTF-8"), "en");
        assert_eq!(normalize_lang_code("POSIX"), "en");
        assert_eq!(normalize_lang_code(""), "en");
    }
}

